// Bundles the MCP Apps widget into one inline script (spec 15.7): a host iframe has no access to our
// site, so everything it needs ships inside the resource. Quiet on stdout: stdio MCP runs after this.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const out = await build({
  entryPoints: [resolve(here, "../src/mcp/widget-client.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2022",
  write: false,
  legalComments: "none",
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
writeFileSync(resolve(here, "../src/mcp/widget-bundle.generated.ts"), `// Generated by scripts/build-widget.mjs.\nexport const WIDGET_JS = ${JSON.stringify(js)};\n`);
